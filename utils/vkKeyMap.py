# -*- coding: utf-8 -*-
"""
vkKeyMap.py —— 虚拟键码(vk) 与 规范键名 的双向映射【唯一真相源】

=====================================================================
为什么需要这个模块（Bug#30 根因回顾）：
    旧版监听端以 char 为第一优先。而 pynput 在 Windows 下生成 char 时
    会参考"当时按住的修饰键"（内部走 ToUnicode），导致：
      · Ctrl+字母 的 char 变成控制字符 '\x01'~'\x1a'
      · Ctrl/Alt+标点 的 char 直接为 None
      · Shift+数字 的 char 变成上档符号 '@' 等，丢失 shift 成员信息
    而 vk（虚拟键码）是物理键位的编号：
      · 不随修饰键变化      —— Ctrl+A 的 vk 永远是 65
      · 不随 CapsLock 变化  —— 大写锁定下字母 vk 不变
      · 不随输入法变化      —— 中文输入法开关不影响 vk
    因此监听端与发送端统一改用 vk 作为身份标识，char 只留容错位。

范围边界（防止未来回头乱扩）：
    · 本表只收录"常规字符键"（数字/字母/小键盘/OEM标点）。
    · 特殊键（space/tab/f1~f12/方向键等）走 pynput 的 name 属性 +
      executor._normalizeAlias 别名体系，不在本表管辖内。
      （这样划分避免把别名逻辑也搬过来，扩大本轮战场）
    · numpad_enter 与主键盘回车共用 VK_RETURN(13)，事件层无法可靠区分，
      故不单列——用户文档口径为"统一写 enter，两处回车均命中"。
    · 仅支持美式布局（决策6）：OEM 键名取物理键位的美式解读，
      其他布局需求出现时再做覆盖表，结构已预留（见文末扩展说明）。
"""

# ---------------------------------------------------------------------
# 正向表：vk -> 规范键名（监听端 executor._normalizeSingleKey 使用）
# ---------------------------------------------------------------------
VK_TO_NAME: dict[int, str] = {
    # ── 主键盘数字行 0~9（vk 48-57 恰好就是 '0'~'9' 的 ASCII）──
    **{vk: chr(vk) for vk in range(48, 58)},

    # ── 字母 a~z（vk 65-90 是大写字母 ASCII；统一转小写存表，
    #    使大小写锁定键对此完全免疫）──
    **{vk: chr(vk).lower() for vk in range(65, 91)},

    # ── 小键盘数字 0~9（numlock 开启时的行为；关闭时系统改发
    #    导航键 vk，自然落到下方导航键语境，无需本表操心）──
    **{vk: f"numpad_{vk - 96}" for vk in range(96, 106)},

    # ── 小键盘运算键五个（决策2独立命名）。
    #    注意：没有 vk 108！106~111 中 108(VK_SEPARATOR) 平时不产生，
    #    历史上只出现在部分欧洲键盘，故跳过不留空壳条目。
    #    对应物理位置：* 和 / 在小键盘右上区，+ - . 在右下区。
    106: "numpad_multiply",
    107: "numpad_add",
    109: "numpad_subtract",
    110: "numpad_decimal",
    111: "numpad_divide",

    # ── OEM 标点行 11 键（Bug#30 主战场，名称一律取美式下档/底位符，
    #    上档效果由用户配置 shift 成员实现，如 shift+= 表示加号）──
    186: ";",     # ;:   (VK_OEM_1)
    187: "=",     # =+   (VK_OEM_PLUS)   ← 原 Bug 直接受害者
    188: ",",     # ,<   (VK_OEM_COMMA)
    189: "-",     # -_   (VK_OEM_MINUS)
    190: ".",     # .>   (VK_OEM_PERIOD)
    191: "/",     # /?   (VK_OEM_2)      ← 原 Bug 直接受害者
    192: "`",     # `~   (VK_OEM_3)
    219: "[",     # [{   (VK_OEM_4)
    220: "\\",    # \|   (VK_OEM_5)      ← 表达式里写反斜杠要转义
    221: "]",     # ]}   (VK_OEM_6)
    222: "'",     # '"   (VK_OEM_7)
}

# ---------------------------------------------------------------------
# 反向表：规范键名 -> vk（发送端 actionHandlers._tokenToPynputObject 使用）
# 用 setdefault 构建：首见者胜。当前正表不含重名，此处纯为防御未来扩展
# 时出现重名映射（例如某天同时收录两处同名字符键）导致发送端不确定。
# ---------------------------------------------------------------------
NAME_TO_VK: dict[str, int] = {}
for _vk, _name in VK_TO_NAME.items():
    NAME_TO_VK.setdefault(_name, _vk)


# ---------------------------------------------------------------------
# 未来扩展口子（本轮不做，只留结构说明）：
#   · 媒体键：176=media_play_pause / 179=media_nexttrack 等，
#     直接往 VK_TO_NAME 里加条目即可，两端自动同步生效；
#   · 非 USB-HID 的扩展键某些键盘驱动会给高 vk (>255)，不在标准域内，
#     不收录，交由归一化函数返回 None 后被忽略。
# ---------------------------------------------------------------------

# ============================ 自测代码 ===============================
# 单独运行本文件即可验证两张表的完整性（python utils/vkKeyMap.py），
# 与项目其他模块零耦合：
#   检查项① 名字无重复：同一规范名绝不允许来自两个不同 vk
#   检查项② 数量正确：10数字 + 26字母 + 10小键盘数 + 5运算 + 11标点 = 62
#   检查项③ 抽查关键样本：本轮 bug 两主角 '=' '/' 必须在表中且指向正确
if __name__ == "__main__":
    # ① 反向去重检查

    #   这里再显式找一遍潜在重复名，正常应输出空列表
    collisions = []
    seen: dict[str, int] = {}
    for vk, nm in VK_TO_NAME.items():
        if nm in seen:
            collisions.append((nm, seen[nm], vk))
        seen[nm] = vk
    print("重名冲突:", collisions or "无 ✅")

    # ② 数量核对
    print(f"正向收录 {len(VK_TO_NAME)} 个 vk（应为 62），"
          f"反向 {len(NAME_TO_VK)} 个（应与正向相等）")

    # ③ 关键样本抽查
    for probe_vk, expect in [(187, "="), (191, "/"),
                             (106, "numpad_multiply"), (65, "a"),
                             (49, "1"), (97, "numpad_1")]:
        got = VK_TO_NAME.get(probe_vk)
        mark = "✅" if got == expect else "❌"
        print(f"{mark} vk={probe_vk} -> {got!r} (期望 {expect!r})")
